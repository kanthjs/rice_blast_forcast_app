# R/about_modal.R

#' Show About App Modal
#' Displays a modal dialog with information about the Rice Disease Risk Tool
show_about_modal <- function() {
    showModal(modalDialog(
        title = "เกี่ยวกับแอปพลิเคชัน (About this App)",
        size = "l",
        easyClose = TRUE,
        div(
            h5("ระบบพยากรณ์ความเสี่ยงโรคไหม้ในข้าว"),
            p(
                "แอปพลิเคชันนี้พัฒนาขึ้นเพื่อช่วยเกษตรกรและผู้เกี่ยวข้องในการประเมินความเสี่ยงของการเกิดโรคไหม้ (Rice Blast) โดยใช้ข้อมูลพยากรณ์อากาศล่วงหน้า 14 วัน จาก Open-Meteo ร่วมกับแบบจำลองทางระบาดวิทยา"
            ),
            hr(),
            h6("แบบจำลองที่ใช้ (Models):"),
            tags$ul(
                tags$li(
                    strong("Classic:"),
                    " พิจารณาความเหมาะสมของสภาพอากาศ (อุณหภูมิ, ความชื้น) เบื้องต้น"
                ),
                tags$li(
                    strong("EDRM:"),
                    " โมเดลละเอียดที่นำอายุข้าว (Rice Age) และปัจจัยความเปียกใบมาคำนวณร่วมกับอุณหภูมิ"
                ),
                tags$li(
                    strong("BUS:"),
                    " คำนวณความเสี่ยงจากจำนวนชั่วโมงที่ใบเปียก (Wet Hours) และอุณหภูมิ"
                ),
                tags$li(
                    strong("BLASTAM:"),
                    " เน้นการตรวจจับช่วงเวลาติดเชื้อ (Infection Period) เพื่อพยากรณ์การระบาด"
                ),
                tags$li(
                    strong("EPIBLA:"),
                    " ประเมินความรุนแรง (Severity) ของโรค โดยพิจารณาความต้านทานของพันธุ์ข้าว"
                )
            ),
            hr(),
            h6("คำแนะนำการใช้งาน:"),
            tags$ol(
                tags$li(
                    "เลือกพื้นที่แปลงนา โดยการคลิกบนแผนที่ หรือค้นหา หรือใช้ตำแหน่งปัจจุบัน"
                ),
                tags$li("ตรวจสอบวันที่เริ่มต้น และสิ้นสุดการพยากรณ์ (เช่น ย้อนหลัง 3 วัน)"),
                tags$li("เลือกโมเดลที่ต้องการในแถบ 'Crop risk models'"),
                tags$li("อ่านผลการวิเคราะห์และความเสี่ยง เพื่อวางแผนการป้องกัน")
            ),
            p(
                class = "text-muted small mt-3",
                "หมายเหตุ: ผลการพยากรณ์ใช้เพื่อประกอบการตัดสินใจเท่านั้น ควรสำรวจแปลงนาจริงร่วมด้วย"
            )
        ),
        footer = modalButton("Close")
    ))
}
